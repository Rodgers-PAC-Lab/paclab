## Chris' joint angle functions from 20250605_3d
def cart2sphere(x, y, z):
    """Convert cartesian to spherical (length, azim, elev)
    
    Azimuth of zero is parallel to x
    Elevation of zero is parallel to z
    
    See figure 5.7.10 here:
    https://math.libretexts.org/Courses/Mount_Royal_University/Calculus_for_Scientists_II/7%3A_Vector_Spaces/5.7%3A_Cylindrical_and_Spherical_Coordinates
    """
    length = np.sqrt(x ** 2 + y ** 2 + z ** 2)
    azim = np.arctan2(y, x)
    elev = np.arccos(z / length)
    assert (azim >= -np.pi).all()
    assert (azim <= np.pi).all()
    return length, azim, elev

def sphere2cart(length, azim, elev):
    """Convert spherical (length, azim, elev) to cartesian"""
    z = length * np.cos(elev)
    
    # Distance in the XY plane
    r = length * np.sin(elev)
    x = r * np.cos(azim)
    y = r * np.sin(azim)

    return x, y, z

def joint_angle(ego, return_rots = False, apply_correction = True):
    """
    Compute joint angles for egocentered data. These are spherical coordinates
    for the distal limb segment in the local joint coordinate frame
    
    ego is assumed to be a Tx3x22 matrix containing
    3D position centered at SpineM for each of the keypoints in mouse22.

    The local joint coordinate frame is defined using a rotation matrix.
    For SpineM, all rotation matrices are the identity matrix
    For SpineF, ShoulderL, and ShoulderR, the rotation matrix is:
    [torsion vector, lateral vector, torso vector]
    
    For all other computed rotation matrices, the z-axis is aligned with
    the proximal limb segment, and the x-axis is defined as the projection
    of the torso vector into the x-y plane. This is unstable when the direction
    of the proximal limb segment approaches the torso vector, leading to gimbal lock.
    
    If apply_correction = True, shift the local xy-basis so that the azimuth
    is circularly mean-centered.
    
    returns: 3 dicts storing the length, azimuth, and elevation time series for the corresponding segment,
             torsions, a (T,) vector with the spinal torsion time series,
             and rots, a dict containing the rotation matrices used if return_rots = True
    """
    ref_dict = {
    'ElbowL': (11, 10),  # left elbow
    'WristL':  (10, 9),   # left wrist

    'ElbowR': (15, 14),   # right elbow
    'WristR': (14, 13),   # right wrist

    'KneeL': (4, 18),  # left knee
    'AnkleL': (18, 17), # left ankle

    'KneeR': (4, 21), # right knee
    'AnkleR': (21, 20), # right ankle

    # Special joints handled differently
    'SpineF': [3],
    'SpineM': [4],
    'ShoulderL': [11],
    'ShoulderR': [15]
    }
    
    rots = {}

    # First use _compute_rotation_matrix for the
    # limb segments
    for r in ref_dict:
        if len(ref_dict[r]) == 2:
            k1 = ref_dict[r][0]
            kv = ref_dict[r][1]            
        
            k1_t = ego[:, :, k1]
            kv_t = ego[:, :, kv]
            
            z = k1_t - kv_t
            x_ref = np.tile(np.array([1,0,0]), (z.shape[0], 1)) # torso vector
            rot = _compute_rotation_matrix(z, x_ref)

            rots[r] = rot
        
    ## rotation matrix for spine m is identity
    rots["SpineM"] = np.stack([np.eye(3) for _ in range(ego.shape[0])])
    ## Rotation matrix for spine f is defined using the "collar matrix."
    #  It has the torso vector as one basis while the other bases define
    #  the "collar plane" which biomechanically should be rigid
    #  in effect, it is constrained to only rotate around the torso axis
    #  and can be used to compute torsion of the upper spine wrt the mid spine
    
    collar = np.concatenate((ego[:, :, 11, np.newaxis] - ego[:, :, 3, np.newaxis], ego[:, :, 15, np.newaxis] - ego[:, :,3, np.newaxis]), axis = 2)
    
    # normalize to enforce rigidity
    collar = collar / np.linalg.norm(collar, axis = 1).reshape(-1, 1, 2)
    
    # compute torsion vector 
    tors = np.average(collar, axis = 2)
    
    # build out spine f something like this
    torso = np.tile(np.array([1,0,0]), (z.shape[0], 1))
    # torso = torso / np.linalg.norm(torso, axis = 1).reshape(-1, 1)
    lateral = np.cross(tors, torso, axis = 1)
    lateral = lateral / np.linalg.norm(lateral, axis = 1).reshape(-1, 1)
    
    tors = np.cross(lateral, torso, axis = 1)
    tors = tors / np.linalg.norm(tors, axis = 1).reshape(-1, 1)
    
    rots["SpineF"] = np.concatenate((-1*tors.reshape(-1, 3, 1), -1*lateral.reshape(-1, 3, 1), torso.reshape(-1, 3, 1)), axis = 2)
    
    # Shoulder rotation matrices are identical to the Spine F basis
    rots["ShoulderL"] = rots["SpineF"].copy()
    rots["ShoulderR"] = rots["SpineF"].copy()

    ## TODO: assert all rotation matrices have a determinant of +1

    ## Compute spherical coordinates for each distal limb segment in the local joint coordinate frame
    ## using cart2sphere
    lengths = {}
    azims = {}
    elevs = {}

    for k in rots:
        if k == "SpineM":
            # Skip this one since it is the global origin
            continue
            
        if k == "SpineF":
            # Measure the torsion as compound angle 
            torsion_dot = np.einsum('ij,ij->i', rots["SpineM"][:, :, 2], -1*rots["SpineF"][:, :, 0])
            torsion = np.arccos(np.clip(torsion_dot, -1.0, 1.0))
            
        else:
            # Grab distal limb vector in global joint cartesian space
            this_joint = ref_dict[k][-1]
            distal_joint = this_joint - 1
            v = ego[:, :, distal_joint] - ego[:, :, this_joint]

            # Project into local joint cartesian space
            v_proj = np.squeeze(rots[k].transpose(0, 2, 1) @ v[:, :, None])

            # Compute spherical coordinates
            lengths[k], azims[k], elevs[k] = cart2sphere(v_proj[:, 0], v_proj[:, 1], v_proj[:, 2])
            
            if apply_correction:
                mu = np.atan2(np.mean(np.sin(azims[k]), axis = 0), 
                              np.mean(np.cos(azims[k]), axis = 0))
                azims[k] -= mu
                azims[k] = (azims[k] + np.pi) % (2*np.pi) - np.pi
                x0 = rots[k][:, :, 0].copy()
                y0 = rots[k][:, :, 1].copy()
                
                rots[k][:, :, 0] = np.cos(mu) * x0 + np.sin(mu) * y0
                rots[k][:, :, 1] = -np.sin(mu) * x0 + np.cos(mu) * y0

    if return_rots:
        return lengths, azims, elevs, torsion, rots

    return lengths, azims, elevs, torsion
            
        
