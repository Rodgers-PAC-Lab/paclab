def keypoints_array2df(arr):
    """Convert an ndarray of dannce keypoints to a labeled DataFrame
    
    `arr` should be DANNCE output loaded by `load_DANNCE`: a 4d ndarray of
    shape (n_frames, n_animals, n_coords, n_keypoints) with n_coords == 3. 
    Only n_animals == 1 is supported: the animal axis will be squeezed if 
    present, and it is okay if it has already been squeezed out.
    This function can be inverted by keypoints_df2array.
    
    This function converts the 3d array to a DataFrame with frame number on the 
    index and (coord, keypoint) on the column MultiIndex. The keypoint order
    is taken from get_skeleton() .
    
    While (keypoint, coord) might make more sense, we keep the (coord, keypoint)
    ordering for compatibility with DANNCE code. Coord is always sliced before
    keypoint. 
    
    Note that the returned DataFrame may be a view of the original array. 
    Use its .copy() method if a new copy is needed.
    
    Returns: DataFrame
        index: Series of 0-indexed frame numbers named "n_frame"
        columns: MultiIndex ('coord', 'keypoint')
            'coord': ('x', 'y', 'z')
            'keypoint': keypoint names from get_skeleton()
        values: same as data in `arr`
    """
    
    # Slice out animal if needed
    if arr.ndim == 4:
        assert arr.shape[1] == 1
        arr = arr[:, 0]
    
    # Get joint_names
    keypoint_names, body_connectivity = get_skeleton()
    
    # Form series for frames, coord, and keypoints
    n_frames = len(arr)
    frame_ser = pandas.Series(range(n_frames), name='n_frame')
    coord_ser = pandas.Series(['x', 'y', 'z'], name='coord')
    keypoint_ser = pandas.Series(keypoint_names, name='keypoint')
    
    # Reshape to (n_frames, n_coords * n_keypoints)
    # This might make a view
    reshaped = arr.reshape(n_frames, len(coord_ser) * len(keypoint_names))
    
    # Labels
    df = pandas.DataFrame(reshaped) # view might be lost here
    df.index = frame_ser
    df.columns = pandas.MultiIndex.from_product([coord_ser, keypoint_ser])   
    
    # Return
    return df

def keypoints_df2array(df):
    """Convert a DataFrame of dannce keypoints to a raw array.
    
    `df` should be a DataFrame with frame number on the index and a 
    MultiIndex ('coord', 'keypoint') on the columns.
    
    This function converts the DataFrame to an unlabeled 3d array in 
    (n_frame, coord, keypoint) axis order. Multi-animal is not supported.
    This function can be inverted by keypoints_array2df.

    Note that the returned array may be a view of the original DataFrame's 
    data. Use its .copy() method if a new copy is needed.
    
    Returns: 3d array
    """
    # Error check
    # TODO: if column levels have been swapped, unswap them here
    assert df.index.name == 'n_frame'
    # assert np.all(df.index.values == np.arange(len(df)))
    assert df.columns.names == ('coord', 'keypoint')
    assert (
        df.columns.get_level_values('coord').unique() == ['x', 'y', 'z']
        ).all()
    
    # Get joint_names and reindex in keypoint order
    keypoint_names, body_connectivity = get_skeleton()
    df = df.reindex(keypoint_names, axis=1, level='keypoint')
    assert (
        df.columns.get_level_values('keypoint').unique() == list(keypoint_names)
        ).all()
    
    # Reshape to (n_frames, n_coords, n_keypoints)
    # This might make a view
    arr = df.values.reshape(len(df), 3, len(keypoint_names))
    
    # Return
    return arr

def load_label3d_data(filename):
    """Load labeled data from a dannce.mat file generated by Label3D
    
    Arguments
        filename : str, full path to a dannce.mat file with labels in it

    Flow
        * Load camera parameters with _parse_camera_parameters
          These include intrinsic and extrinsic parameters
        * Load points with _parse_labeled_points
          These are points in the undistorted (rectilinear) image
    
    Returns: dict with the following items
        'camera_names' : list of camera names. Used to index all other 
            returned items
        'camera_parameters' : dict with the following items
            'scene_matrix' : DataFrame, scene matrix (K) for each camera
            'rotation_matrix' : DataFrame, rotation matrix (r) for each camera
            'translation_vector' : DataFrame, translation vector (t) for each
            'radial_distortion' : DataFrame, RDistort for each camera
            'tangential_distortion' : DataFrame, TDistort for each camera
        'points_2d' : DataFrame
            index : MultiIndex (camera, frame_number)
            columns : MultiIndex (joint, coord)
            values : point in the undistorted (rectilinear) image
        'points_3d' : DataFrame
            index : frame number
            columns : MultiIndex (joint, coord)
            values : point in the 3d space
    """
    # Load data
    data = scipy.io.loadmat(filename)

    # Get camera names
    cam_names = [val.item() for val in data['camnames'].squeeze()]

    # Parse camera parameters
    camera_parameters = _parse_camera_parameters(data)

    # Parse points
    points_2d, points_3d = _parse_labeled_points(data)
    
    # Return
    return {
        'camera_names': cam_names,
        'camera_parameters': camera_parameters,
        'points_2d': points_2d,
        'points_3d': points_3d,
        }

def egocenter_and_align(
    data, 
    center_keypoints=('SpineM', 'SpineF'), 
    align_keypoints=('SpineM', 'SpineF'), 
    level_pitch=False,
    warn=True,
    ):
    """Egocenter and align 3D pose data.
    
    Each frame is translated so that the centroid of the keypoints named in
    `center` sits at the origin, then rotated so that the alignment vector from 
    `align[0]` to `align[1]` points toward +x. 
    
    If `level_pitch`, the alignment vector will have no z-component and lie
    along +x; otherwise, it will retain its original pitch in the xz-plane. 
    In either case, there is no correction for roll.
    
    All rotations are extrinsic and performed in "yaw before pitch" order.

    TODO: redundant functionality available in egocenter.

    Arguments
    ---
    data : DataFrame containing keypoints from keypoints_array2df
        index: frame
        columns: MultiIndex (coord, keypoint)
    center_keypoints : list-like of any length
        Centroid of the keypoints in this list will be sent to the origin
    align_keypoints : list-like of length 2
        'alignment vector' goes from align_keypoints[0] to align_keypoints[1]
    level_pitch : bool
        If False, rotate around z only (yaw). The alignment vector lands in
        the xz-plane but its z-component is preserved.
        If True, additionally rotate around y so the alignment vector lands
        along +x with no z-component.
    warn : bool
        If True, issue warnings when the alignment vector is too short or
        nearly vertical, in which case the results are unreliable.
    
    Returns: dict with the following items
    ---
    'aligned': DataFrame with the same index and columns as `data`
        Centered and aligned keypoints in millimeters
    'translation': DataFrame with cols ('x', 'y', 'z'); same index as `data`
        Translation that was applied to each frame
    'alignment_vector': DataFrame with same shaped as `translation`
        Original alignment_vector computed on each frame
        Useful for finding frames where alignment couldn't be done well
    'rotation': scipy.spatial.Rotation 
        Rotation that was applied to each frame
        Rotation.as_matrix() has shape (n_frames, 3, 3)
    """
    
    ## Get size
    n_frames = len(data)
    n_keypoints = data.columns.get_level_values('keypoint').nunique()
    assert data.shape[1] == 3 * n_keypoints
    assert data.columns.names == ['coord', 'keypoint']
    assert (
        list(data.columns.get_level_values('coord').unique()) == 
        ['x', 'y', 'z'])
    
    
    ## Translate to send the centroid of these keypoints to the origin
    translation = -data.reindex(
        center_keypoints, level='keypoint', axis=1).T.groupby('coord').mean().T
    
    # Apply
    ego = data.add(translation, level='coord', axis=1)
    
    
    ## Compute the way the mouse is pointing in each frame in (x, y, z)
    v = (
        ego.xs(align_keypoints[1], level='keypoint', axis=1) -
        ego.xs(align_keypoints[0], level='keypoint', axis=1))

    if warn:
        # Check for frames where v is too short (align_keypoints are coincident)
        v_len = np.sqrt((v ** 2).sum(axis=1))
        n_bad_frames = (v_len < 0.01 * v_len.median()).sum()
        if n_bad_frames > 0:
            print(f'warning: too short alignment vector on {n_bad_frames} frames')

        # Check for frames where the mouse is nearly vertical
        # Everything will still work (no nulls), but the yaw rotation will be 
        # dominated by noise and thus meaningless
        # TODO: align by another segment in this case - head or forelimbs maybe?
        z_proj = v['z'] / v_len
        n_bad_frames = (z_proj.abs() > .999).sum()
        if n_bad_frames > 0:
            print(f'warning: near-vertical mouse on {n_bad_frames} frames')


    ## Correct for yaw
    # Compute the angle of `v` in the XY plane - the "heading" - on each frame
    initial_heading = np.arctan2(v['y'], v['x'])

    # Compute XY rotation (yaw) on each frame that will point the XY 
    # component of `v` toward the +x axis on each frame
    # That is, a rotation of `-initial_heading` about the Z axis
    # R_yaw.as_matrix() has shape (n_frames, 3, 3)
    R_yaw = scipy.spatial.transform.Rotation.from_euler(
        'Z', 
        -initial_heading.values[:, None], # scipy 1.17.1 requires 2d input
        )
    
    
    ## Optionally correct for pitch
    # Compute a second rotation to pitch the mouse horizontal, that is, 
    # to make `v` point toward +x in XYZ (not just XY)
    if level_pitch:
        # Compute the component in the xy plane
        # After `R_yaw` corrects yaw, `v` will become (horiz, 0, z)
        horiz = np.sqrt(v['x'] ** 2 + v['y'] ** 2)
        initial_pitch = np.arctan2(v['z'], horiz)

        # Rotate about Y to send initial_pitch to flat
        # Note that it is +initial_pitch not -initial_pitch because of the
        # right-hand rule (positive rotation send +z to +x)
        R_pitch = scipy.spatial.transform.Rotation.from_euler(
            'Y', initial_pitch)
        
        # Compose the two rotations: yaw first, then pitch
        # (Note that the right matrix is applied first)
        R = R_pitch * R_yaw  
    
    else:
        R = R_yaw
    
    
    ## Apply the rotation
    # reshape `ego` to (frames, old_coords, keypoints) or fjk
    ego_arr = ego.values.reshape((n_frames, 3, n_keypoints))
    
    # R.as_matrix (frames, new_coords, old_coords) or fij
    # Result: (frames, new_coords, keypoints) or fik
    # Note that this is equivalent to simply: R.as_matrix() @ egoarr
    rotated = np.einsum('fij,fjk->fik', R.as_matrix(), ego_arr)
    
    # Reshape rotated to be like ego
    rotated = rotated.reshape((n_frames, -1))
    rotated_df = pandas.DataFrame(rotated, index=ego.index, columns=ego.columns)

    
    ## Check
    # This should point toward x
    new_v = (
        rotated_df.xs(align_keypoints[1], level='keypoint', axis=1) -
        rotated_df.xs(align_keypoints[0], level='keypoint', axis=1))
    assert new_v['y'].abs().max() < 1e-6
    if level_pitch:
        assert new_v['z'].abs().max() < 1e-6
    
    
    ## Return
    return {
        'aligned': rotated_df,
        'translation': translation,
        'rotation': R,
        'alignment_vector': v,
        }

def invert_egocenter_and_align(egocentered_d):
    """Inverts the transformation performed by egocenter_and_align
    
    egocentered_d : output of egocenter_and_align
    
    Returns : DataFrame that is hopefully allclose to the original keypoints
    """
    # Reshape
    centered = egocentered_d['aligned']
    centered_arr = centered.values.reshape(len(centered), 3, -1)
    
    # Unrotate
    unrotate_R = egocentered_d['rotation'].as_matrix().swapaxes(1, 2)
    unrotated = unrotate_R @ centered_arr
    unrotated = pandas.DataFrame(
        unrotated.reshape(len(centered), -1),
        index=centered.index, columns=centered.columns)
    
    # Untranslate
    untranslate_vec = -egocentered_d['translation']
    reconstructed = unrotated + untranslate_vec
    
    # Return
    return reconstructed

def define_joints():
    """Returns each joint as its (proximal, central, distal) keypoints.
    
    Each joint is a tuple of (proximal, central, distal) keypoint names.
    The joint is located at the central keypoint, and is defined by the 
    geometric relationship between the proximal segment and distal segment.
    The joint is named by its (central, distal) keypoints.
    
    SpineM and SpineF are special in the sense that either can be considered
    proximal to the other for the purpose of defining a proximal segment 
    along the spine. All other joints are located in a well-defined tree
    from proximal to distal.
    
    This list of joints is complete in the sense that every keypoint appears
    as "distal" exactly once, and its "proximal" and "central" counterparts
    are uniquely defined. However, note that SpineF and SpineM appear multiple
    times as the "central" joint (e.g., shoulders, hips, and head).
    
    Returns: dict joint_name -> (proximal, central, distal) keypoint names
    """
    # Joint definitions: name -> (proximal, central, distal) keypoint names
    joint_dict = {
        # Forelimb: SpineM -> SpineF -> Shoulder -> Elbow -> Wrist -> Forepaw
        'SpineF_ShoulderL':     ('SpineM', 'SpineF', 'ShoulderL'),
        'ShoulderL_ElbowL':     ('SpineF', 'ShoulderL', 'ElbowL'),
        'ElbowL_WristL':        ('ShoulderL', 'ElbowL', 'WristL'),
        'WristL_ForepawL':      ('ElbowL', 'WristL', 'ForepawL'),
        'SpineF_ShoulderR':     ('SpineM', 'SpineF', 'ShoulderR'),
        'ShoulderR_ElbowR':     ('SpineF', 'ShoulderR', 'ElbowR'),
        'ElbowR_WristR':        ('ShoulderR', 'ElbowR', 'WristR'),
        'WristR_ForepawR':      ('ElbowR', 'WristR', 'ForepawR'),
        
        # Hindlimb chain: SpineF -> SpineM -> Knee -> Ankle -> Hindpaw
        # TODO: label HipL/R and insert into the chain
        'SpineM_KneeL':         ('SpineF', 'SpineM', 'KneeL'),
        'KneeL_AnkleL':         ('SpineM', 'KneeL', 'AnkleL'),
        'AnkleL_HindpawL':      ('KneeL', 'AnkleL', 'HindpawL'),
        'SpineM_KneeR':         ('SpineF', 'SpineM', 'KneeR'),
        'KneeR_AnkleR':         ('SpineM', 'KneeR', 'AnkleR'),
        'AnkleR_HindpawR':      ('KneeR', 'AnkleR', 'HindpawR'),
        
        # Axial chain: SpineF -> SpineM -> Tail(base) -> Tail(mid) -> Tail(end)
        'SpineM_Tail(base)':    ('SpineF', 'SpineM', 'Tail(base)'),
        'Tail(base)_Tail(mid)': ('SpineM', 'Tail(base)', 'Tail(mid)'),
        'Tail(mid)_Tail(end)':  ('Tail(base)', 'Tail(mid)', 'Tail(end)'),
        
        # Head: SpineM -> SpineF -> Snout
        # TODO: convert SpineF_EarL and SpineF_EarR to head_roll and head_yaw
        'SpineF_Snout':         ('SpineM', 'SpineF', 'Snout'),
        'SpineF_EarL':          ('SpineM', 'SpineF', 'EarL'),
        'SpineF_EarR':          ('SpineM', 'SpineF', 'EarR'),
        }
    
    return joint_dict

def compute_compound_joint_angles(data):
    """Compute compound angles at each joint of egocentered 3D pose data.
    
    The compound angle at joint J with proximal neighbor P and distal
    neighbor D is the angle between vectors J->P and J->D, computed as
    arccos(u . v / (|u| |v|)) and in the range [0, pi].
    A straight joint yields pi; a fully folded joint gives 0.
    
    The same angle may be obtained as the elevation angle from
    compute_spherical_joint_angles; however, this function is simpler. 
    
    data : DataFrame
        index: frame
        columns: MultiIndex (coord, joint), coord in {'x', 'y', 'z'}
        Egocentering and alignment is irrelevant for compound angles
    
    Returns: DataFrame
        index: same as `data`
        columns: '{central}_{distal}' for each entry in define_joints()
        values: compound angle in radians, in [0, pi]
    """
    
    ## Error check no nulls
    assert not data.isnull().any().any()
    
    
    ## Compute one compound angle per joint per frame
    # Get the joint definitions
    joint_dict = define_joints()
    
    # Iterate over joints
    angles = {}    
    for joint_label, (proximal, central, distal) in joint_dict.items():
        
        # Get coordinates of the three keypoints on every frame
        # Each is a DataFrame with columns x, y, z and one row per frame
        P = data.xs(proximal, level='keypoint', axis=1)
        J = data.xs(central, level='keypoint', axis=1)
        D = data.xs(distal, level='keypoint', axis=1)
        
        # Vectors from central keypoint to each neighbor
        u = P - J
        v = D - J
        
        # Cosine of the angle between u and v
        u_norm = np.sqrt((u ** 2).sum(axis=1))
        v_norm = np.sqrt((v ** 2).sum(axis=1))
        cos_angle = (u * v).sum(axis=1) / (u_norm * v_norm)
        
        # Clip to avoid floating point issues causing null angles
        cos_angle_clipped = cos_angle.clip(-1, 1)
        
        # Error check that angle is not null (would happen if either u or v
        # has zero length, i.e., coincident keypoints)
        assert not cos_angle_clipped.isnull().any()
        
        # Compute angle and store
        angles[joint_label] = np.arccos(cos_angle_clipped)
    
    
    ## Assemble into a single DataFrame
    # `angles` is a dict of Series; concat gives columns in insertion order
    result = pandas.concat(angles, axis=1)
    result.columns.name = 'joint'
    
    return result

def compute_local_basis(z, x_ref):
    """Build a right-handed orthonormal basis from two vectors.

    `z` and `x_ref` are each np.array of shape (n_frames, 3).

    For each frame, returns a 3x3 rotation matrix whose columns are the
    unit basis vectors of a local coordinate frame:
        +z = z, normalized
        +x = component of x_ref orthogonal to +z (Gram-Schmidt)
        +y = +z cross +x 
    
    The output R, when applied to a world-frame vector v as R.T @ v, gives
    that vector's components in the local frame. Equivalently, R @ e_local
    gives a local basis vector in world coords (e.g., R @ [0, 0, 1] = +z).
    
    Singularity warning: when z and x_ref are near parallel (or anti-parallel), 
    the results are likely to be numerically unstable. When they are exactly
    parallel, nans will be returned, without issuing any warnings.
    
    TODO: Redundant with _compute_rotation_matrix
    
    Returns: np.array of shape (n_frames, 3, 3)
        R[f, :, 0] = +x of frame f, R[f, :, 1] = +y, R[f, :, 2] = +z.
    """
    # Helper function to suppress warnings
    def normalize(v):
        # Compute norm and fill zeros with nans to avoid RuntimeWarning
        norm = np.linalg.norm(v, axis=1)[:, None]
        norm[norm == 0] = np.nan
        return v / norm
    
    # Normalize z and x_ref
    z_norm = normalize(z)
    x_ref_norm = normalize(x_ref)
    
    # Gram-Schmidt
    # Compute `y` as z cross x_ref
    y = np.cross(z_norm, x_ref_norm)
    y_norm = normalize(y)
    
    # Compute `x` as y cross z
    # Renormalize in case of numerical error
    x_norm = normalize(np.cross(y_norm, z_norm))
    
    # Stack along last axis
    res = np.stack([x_norm, y_norm, z_norm], axis=2)
    
    return res

def compute_spherical_joint_angles(data, warn=True):
    """Compute spherical joint angles (azimuth, elevation).

    Each joint (i.e. tuple of proximal, central, and distal keypoint) is
    uniquely specified by its distal keypoint. This function will return
    two spherical angles (azimuth and elevation) and a length for each joint.

    SpineM and SpineF define the central segment (most proximal nodes of the
    pose tree). Note that the ordering is SpineM>SpineF>forelimbs but
    SpineF>SpineM>hindlimbs. To enable reconstruction at the same location
    and orientation as `data`, the original keypoints of SpineM and SpineF
    are returned (somewhat redundant given the centering).
    
    For all other joints on each frame, we build a right-handed local coordinate 
    frame at the central keypoint using the proximal segment and a global 
    reference vector. The distal segment vector (central -> distal) is 
    projected into this local frame and expressed in spherical coordinates 
    (length, azimuth, elevation).
    
    Local frame construction for each joint on each frame:
        +z: unit vector from central toward proximal (along proximal segment)
        +x: Gram-Schmidt projection of the global reference into
            the plane perpendicular to +z
        +y: +z cross +x (completes the right-handed frame)

    That is, +x is as close to the global reference as possible, given the 
    proximal segment vector +z.

    Interpretation of the angles:
        elevation: angle in [0, pi] between distal and proximal segment (+z). 
            0 = distal folded back along proximal
            pi/2 = distal perpendicular to proximal
            pi = distal fully extended away from proximal
        azimuth: angle in [-pi, pi] of distal seg projected on local xy-plane
            0 = points toward global reference (currently mouse's left)
            pi/2 = points to +y (CCW from +x when viewed from prox to central)

    The third rotational DoF (roll about the proximal segment's long axis) 
    is not recoverable, although one could choose to relabel distal azimuth
    as proximal roll.
    
    Note that the 'elevation' angle is the same as the 'compound' angle 
    from compute_compound_joint_angles.

    Currently we use the world Y-axis (which points to the mouse's left) as 
    the global reference. (Point of confusion: local +x is close to global +Y).
    The rationale is that singularities occur when the proximal segment is 
    nearly parallel to the reference vector, and the global Y-axis is least 
    likely to be parallel to any of the segments. The torso vector (world X) 
    is a particularly troublesome choice because the spine segment is nearly 
    always oriented along world X, and the spine segment is the proximal 
    segment for many joints. 
    
    Arguments
        data : DataFrame of yaw-aligned keypoints from `egocenter`
            index: frame
            columns: MultiIndex (coord, joint), coord in {'x', 'y', 'z'}
            Yaw-aligned keypoints are required in order for the global reference
            to make sense.
        warn : bool, if True print warning for collinear joints
    
    Returns: dict with following items
        joint_angles: DataFrame
            columns: MultiIndex (joint, coord)
                Note that this is the opposite of the level ordering for `data`
            values: angle in radians or length in mm
        local_basis_vectors: DataFrame
            columns: MultiIndex (joint, world, local)
        collinearity: DataFrame
            columns: joint
            values: dot product of proximal segment and reference vector
        spine_keypoints: DataFrame
            columns: MultiIndex (coord, joint) with joints {'SpineM', 'SpineF'}
            values: SpineM and SpineF positions in the centered frame
    
    Note that every returned DataFrame has the same index as `data`
    """
    
    # Error check no nulls
    assert not data.isnull().any().any()
    
    # Number of frames, used throughout
    n_frames = len(data)
    
    # Joint definitions
    joint_dict = define_joints()

    # Extract SpineM and SpineF positions
    # Store and return these positions to enable reconstruction 
    # (required to account for centering)
    spine_keypoints = data.reindex(
        ['SpineF', 'SpineM'], level='keypoint', axis=1)

    
    ## Compute spherical angles for each joint
    # Store angles and debugging information for each joint
    angles_l = []
    frame_matrix_l = []
    collinearity_l = []
    keys_l = []
    
    # Iterate over joints
    for joint_label, (proximal, central, distal) in joint_dict.items():
        
        # Get keypoint coordinates on every frame as (n_frames, 3) arrays
        P = data.xs(proximal, level='keypoint', axis=1).values
        J = data.xs(central, level='keypoint', axis=1).values
        D = data.xs(distal, level='keypoint', axis=1).values
        
        # Proximal segment: from central toward proximal. This is +z of the
        # local frame.
        proximal_segment = P - J
        
        # Reference vector
        # Shape (n_frames, 3) so it can be passed to compute_local_basis
        # TODO: consider per-joint reference vector
        v_ref = np.tile(np.array([0., 1., 0.]), (n_frames, 1))

        # Collinearity check
        dot = pandas.Series(
            np.sum(proximal_segment * v_ref, axis=1) / 
            np.linalg.norm(proximal_segment, axis=1) / 
            np.linalg.norm(v_ref, axis=1),
            index=data.index,
            )
        
        # Build local frame via Gram-Schmidt. R has shape (n_frames, 3, 3)
        R = compute_local_basis(proximal_segment, v_ref)
        
        # Error check
        assert not np.isnan(R).any()
        
        # Distal segment: from central toward distal, in world coordinates
        distal_segment = D - J
        
        # Project distal segment into the local frame. 
        # R[f] has basis vectors as columns, so R[f].T maps world -> local.
        # einsum 'fji,fj->fi' contracts on the world-frame axis (j),
        # leaving (frame, local axis)
        v_local = np.einsum('fji,fj->fi', R, distal_segment)
        
        # Convert local-frame distal vector to spherical coordinates.
        length, azim, elev = cart2sphere(
            v_local[:, 0], v_local[:, 1], v_local[:, 2])
        
        # Convert angles to DataFrame
        joint_angles = pandas.DataFrame.from_dict(
            {'length': length, 'azim': azim, 'elev': elev})
        joint_angles.index = data.index
        
        # Convert frame matrix to DataFrame
        frame_matrix = pandas.DataFrame(R.reshape(n_frames, -1))
        frame_matrix.index = data.index
        frame_matrix.columns = pandas.MultiIndex.from_product([
            pandas.Series(['x', 'y', 'z'], name='world'),
            pandas.Series(['x', 'y', 'z'], name='local'),
            ])
        
        # Store
        angles_l.append(joint_angles)
        frame_matrix_l.append(frame_matrix)
        collinearity_l.append(dot)
        keys_l.append(joint_label)
    
    
    ## Concat over joints
    big_angles = pandas.concat(
        angles_l, keys=keys_l, names=['joint', 'coord'], axis=1)
    big_frame_matrix = pandas.concat(
        frame_matrix_l, keys=keys_l, names=['joint'], axis=1)
    big_collinearity = pandas.concat(
        collinearity_l, keys=keys_l, names=['joint'], axis=1)


    ## Errors and warnings
    # Error check no nulls in output
    assert not big_angles.isnull().any().any()
    
    # Warning on collinearity
    if warn:
        print("warning: this many joints near collinear")
        print((big_collinearity.abs() > 0.99).mean().sort_values())
    
    
    ## Return
    return {
        'joint_angles': big_angles,
        'local_basis_vectors': big_frame_matrix,
        'collinearity': big_collinearity,
        'spine_keypoints': spine_keypoints,
        }

def simplify_spherical_angles(spherical_angles):
    """Simplify full (invertible) set of angles to a reduced (interpretable) one
    
    Workflow
    - Demeans the azimuth to avoid the wraparound 
    - Drop lengths (no biomechanical meaning)
      TODO: extract animal size estimate from this for scaling?
    - Drop the azimuths from joints for which it doesn't really map onto
      anatomical meaning, which is all that aren't connected to the spine
    - TODO: relabel the resulting angles with anatomical names like
      "shoulder_rotation" or whatever
    - Converts straight elevation from 2*pi to zero 
      TODO: do this upstream in compute_
    
    spherical_angles : DataFrame
        Obtained from computer_spherical_joint_angles
        columns : MultiIndex (joint, coord)
        index : n_frame
        values : angles in radians
    
    Returns : DataFrame
        A subset of columns of spherical_angles, with the level 'azim'
        replaced by 'azim_demeaned'
    """
    ## Transform azimuth
    # Demean azim
    # TODO: make this demeaning optional
    azim = spherical_angles.xs('azim', level='coord', axis=1)
    azim_demeaned = azim.sub(scipy.stats.circmean(azim, axis=0))
    azim_demeaned = np.mod(azim_demeaned + np.pi, 2 * np.pi) - np.pi

    # Replace azim with azim_demeaned
    to_concat = pandas.concat(
        [azim_demeaned], keys=['azim_demeaned'], names=['coord'], axis=1
        ).swaplevel(axis=1)
    spherical_angles = pandas.concat(
        [spherical_angles, to_concat], axis=1, verify_integrity=True
        ).sort_index(axis=1)
    spherical_angles = spherical_angles.drop('azim', axis=1, level='coord')


    ## Finish spherical angles
    # Drop length, which has no biomechanical meaning
    spherical_angles = spherical_angles.drop('length', axis=1, level='coord')

    # Drop azimuths that are poorly fit
    spherical_angles = spherical_angles.drop([
        ('Tail(base)_Tail(mid)', 'azim_demeaned'), # somewhat dispersed - might be okay though
        ('Tail(mid)_Tail(end)', 'azim_demeaned'), # biomodal, often collinear with ref vector
        ('WristR_ForepawR', 'azim_demeaned'), # assume all wrist movement is flexion, because
        ('WristL_ForepawL', 'azim_demeaned'), #   abduction is small and +y is not the right axis
        ('AnkleR_HindpawR', 'azim_demeaned'), # assume all ankle movement is flexion, because
        ('AnkleL_HindpawL', 'azim_demeaned'), #   abduction is small and +y is not the right axis
        #('SpineF_Snout', 'azim_demeaned'), # dispersed, seems redundant with head roll
        ('SpineF_EarL', 'azim_demeaned'), # mixture of roll and turn, redundant with other ear
        ('SpineF_EarR', 'azim_demeaned'), # mixture of roll and turn, redundant with other ear
        ], axis=1)
    
    
    ## Convert "straight" from pi to zero
    elev_mask = spherical_angles.columns.get_level_values('coord') == 'elev'
    val = spherical_angles.loc[:, elev_mask].values
    spherical_angles.loc[:, elev_mask] = np.pi - val


    ## Return
    return spherical_angles

