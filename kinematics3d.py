## Angle functions

def __compute_compound_angle(pred, k1, kv, k2, degrees = True, index_base = 1):
    '''
    Compute the 3 point angle between keypoints across time
    
    pred: DANNCE prediction data. Expected to be shape Tx1x3xK or Tx3xK
    k1: keypoint to use as first end point
    kv: keypoint to use as vertex point
    k2: kepoint to use as second end point
    degrees: boolean flag that returns angle in degrees if true and in radians if false. Default: true
    index_base: specifies whether joint indices are specified as indexed from 0 or 1. Default: 1
    
    Returns angle: a T x 1 numpy array containing the angle between keypoints in degrees at each time point
    '''
    if len(pred.shape) > 3:
        pred = np.squeeze(pred)

    if index_base == 1:
        k1 -= 1
        kv -= 1
        k2 -= 1
    elif index_base != 0:
        raise ValueError
    
    v1 = pred[:,:,k1] - pred[:,:,kv]
    v2 = pred[:,:,k2] - pred[:,:,kv]
    
    v1mag = np.sqrt(v1[:,0]**2 + v1[:,1]**2 + v1[:,2]**2)
    v2mag = np.sqrt(v2[:,0]**2 + v2[:,1]**2 + v2[:,2]**2)
    
    v1norm = v1 / np.column_stack((v1mag, v1mag, v1mag))
    v2norm = v2 / np.column_stack((v2mag, v2mag, v2mag))
    
    dot = np.sum(v1norm * v2norm, axis=1)

    angle = np.arccos(dot)
    
    if degrees:
        angle = np.degrees(angle)
        
    return angle


def _compute_rotation_matrix(z, x_ref):
    '''
    Compute rotation matrix given two vectors using
    Gram-schmidt
    z specifies the local z-axis
    x_ref is the vector whose projection into the x-y
    plane becomes the local x-axis

    Returns a T x 3 x 3 matrix containing rotation matrices
    across time, with the basis stored along the columns
    '''
    
    z_mag = np.sqrt(z[:, 0]**2 + z[:, 1]**2 + z[:, 2]**2)
    x_ref_mag = np.sqrt(x_ref[:, 0]**2 + x_ref[:, 1]**2 + x_ref[:, 2]**2)

    z_norm = z / np.column_stack((z_mag, z_mag, z_mag))
    x_ref_norm = x_ref / np.column_stack((x_ref_mag, x_ref_mag, x_ref_mag))
    
    y = np.cross(z_norm, x_ref_norm)

    y_mag = np.sqrt(y[:, 0]**2 + y[:, 1]**2 + y[:, 2]**2)
    y_norm = y / np.column_stack((y_mag, y_mag, y_mag))

    x = np.cross(y_norm, z_norm)
    x_mag = np.sqrt(x[:, 0]**2 + x[:, 1]**2 + x[:, 2]**2)
    x_norm = x / np.column_stack((x_mag, x_mag, x_mag))

    z_norm = np.expand_dims(z_norm, axis = 2)
    y_norm = np.expand_dims(y_norm, axis = 2)
    x_norm = np.expand_dims(x_norm, axis = 2)

    if np.any(z_mag < 1):
        print("Warning: bone is very small!")
    if np.any(y_mag < 1e-1):
        print("Warning: bones are likely colinear!")
    if np.any(x_ref_mag < 1):
        print("Warning: reference bone is very small!")
    return np.concatenate((x_norm, y_norm, z_norm), axis = 2)

def rodrigues_rotation(v1, v2):
    '''
    Compute a rotation matrix using Rodrigues' method given two vectors, which are
    assumed to be two vectors representing edges at a node along the kinematic
    chain.
    TODO: vectorize over a time axis
    
    Returns R, a rotation matrix
    '''
    
    # Find axis of rotation
    a = np.cross(v1, v2) / np.linalg.norm(np.cross(v1, v2))
    
    # Find angle of rotation (equivalent to flexion angle)
    theta = np.arccos(v1, v2) / (np.linalg.norm(v1) * np.linalg.norm(v2))
    
    # Build cross product matrix of a
    a_cross = np.array([[0, -a[2], a[1]],
                        [a[2], 0, -a[0]],
                        [-a[1], a[0], 0]])
    # Apply Rodrigues
    R = np.eye(3) + np.sin(theta) * a_cross + (1 - np.cos(theta)) * np.linalg.matrix_power(a_cross, 2)
    
    return R
    
def angles_from_rodrigues(R):
    '''
    Given a rotation matrix computed with Rodrigues' method from an axis-angle 
    representation, extract joint angles. Note that these are constrained
    Euler angles with the arbitrary axial rotation removed.
    
    Returns phi, theta measuring the azimuth and flexion at a joint
    '''
    
    phi = np.atan2(R[1, 2], R[0, 2])
    theta = np.arccos(R[2, 2])
    
    return phi, theta
    

